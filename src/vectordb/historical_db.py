"""
historical_db.py — ChromaDB-backed vector store of canonical solar flare profiles.

Pre-seeded with ~50 well-documented historical flare events spanning five
decades.  Each entry stores the event's metadata and a 128-d light-curve
embedding generated by StatisticalEmbedder.

The synthetic light curves are modelled as FRED (Fast Rise Exponential Decay)
profiles — the same physics used in the project's test fixtures — with
parameters calibrated to published peak fluxes and durations.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

import numpy as np


@dataclass
class HistoricalFlareEntry:
    """A single historical flare record stored in the vector database."""

    event_id: str
    event_name: str
    date: str           # ISO-8601
    flare_class: str    # e.g. "X17.2"
    peak_flux: float    # W/m² (GOES 1–8 Å equivalent)
    duration_min: float
    description: str
    embedding: np.ndarray = field(repr=False)  # 128-d


@dataclass
class HistoricalMatch:
    """Result of a similarity search against the historical database."""

    event_name: str
    date: str
    flare_class: str
    similarity: float   # cosine similarity, 0–1
    description: str
    peak_flux: float
    duration_min: float
    narrative: str       # human-readable comparison sentence


class HistoricalFlareDB:
    """
    ChromaDB-backed vector store for historical solar flare profiles.

    Falls back to an in-memory brute-force search if ChromaDB is not
    installed (for environments that can't install it).

    Parameters
    ----------
    persist_dir : str or None
        Path to persist the ChromaDB data.  If None, uses in-memory mode.
    collection_name : str
        Name of the ChromaDB collection.
    embedding_dim : int
        Dimensionality of the embeddings (must match the embedder).
    """

    def __init__(
        self,
        persist_dir: Optional[str] = None,
        collection_name: str = "historical_flares",
        embedding_dim: int = 128,
    ):
        self.embedding_dim = embedding_dim
        self._chromadb_available = False
        self._collection = None
        self._fallback_entries: list[HistoricalFlareEntry] = []

        try:
            import chromadb
            self._chromadb_available = True

            if persist_dir:
                client = chromadb.PersistentClient(path=persist_dir)
            else:
                client = chromadb.Client()

            self._collection = client.get_or_create_collection(
                name=collection_name,
                metadata={"hnsw:space": "cosine"},
            )
        except ImportError:
            pass

        # Auto-seed if empty
        if self._is_empty():
            self._seed_canonical_events()

    def _is_empty(self) -> bool:
        if self._chromadb_available and self._collection is not None:
            return self._collection.count() == 0
        return len(self._fallback_entries) == 0

    def add_event(self, entry: HistoricalFlareEntry) -> None:
        """Insert a historical flare event into the database."""
        if self._chromadb_available and self._collection is not None:
            self._collection.add(
                ids=[entry.event_id],
                embeddings=[entry.embedding.tolist()],
                metadatas=[{
                    "event_name": entry.event_name,
                    "date": entry.date,
                    "flare_class": entry.flare_class,
                    "peak_flux": float(entry.peak_flux),
                    "duration_min": float(entry.duration_min),
                    "description": entry.description,
                }],
            )
        else:
            self._fallback_entries.append(entry)

    def search_similar(self, embedding: np.ndarray, top_k: int = 5) -> list[HistoricalMatch]:
        """
        Find the top-k most similar historical flare profiles.

        Parameters
        ----------
        embedding : np.ndarray
            128-d query embedding (L2-normalised).
        top_k : int
            Number of results to return.

        Returns
        -------
        list[HistoricalMatch]
        """
        if self._chromadb_available and self._collection is not None:
            return self._search_chromadb(embedding, top_k)
        return self._search_fallback(embedding, top_k)

    def count(self) -> int:
        if self._chromadb_available and self._collection is not None:
            return self._collection.count()
        return len(self._fallback_entries)

    # ── ChromaDB search ───────────────────────────────────────────────────

    def _search_chromadb(self, embedding: np.ndarray, top_k: int) -> list[HistoricalMatch]:
        results = self._collection.query(
            query_embeddings=[embedding.tolist()],
            n_results=min(top_k, self._collection.count()),
        )

        matches = []
        if results and results["ids"] and results["ids"][0]:
            for i, eid in enumerate(results["ids"][0]):
                meta = results["metadatas"][0][i]
                distance = results["distances"][0][i] if results["distances"] else 0.0
                # ChromaDB cosine distance = 1 - cosine_similarity
                similarity = max(0.0, 1.0 - distance)

                narrative = _build_narrative(
                    meta["event_name"], meta["date"], meta["flare_class"], similarity
                )
                matches.append(HistoricalMatch(
                    event_name=meta["event_name"],
                    date=meta["date"],
                    flare_class=meta["flare_class"],
                    similarity=round(similarity, 4),
                    description=meta["description"],
                    peak_flux=meta["peak_flux"],
                    duration_min=meta["duration_min"],
                    narrative=narrative,
                ))
        return matches

    # ── Fallback brute-force search ───────────────────────────────────────

    def _search_fallback(self, embedding: np.ndarray, top_k: int) -> list[HistoricalMatch]:
        if not self._fallback_entries:
            return []

        sims = []
        for entry in self._fallback_entries:
            cos_sim = float(np.dot(embedding, entry.embedding) / (
                max(np.linalg.norm(embedding), 1e-12) *
                max(np.linalg.norm(entry.embedding), 1e-12)
            ))
            sims.append((cos_sim, entry))

        sims.sort(key=lambda x: x[0], reverse=True)

        matches = []
        for sim, entry in sims[:top_k]:
            narrative = _build_narrative(entry.event_name, entry.date, entry.flare_class, sim)
            matches.append(HistoricalMatch(
                event_name=entry.event_name,
                date=entry.date,
                flare_class=entry.flare_class,
                similarity=round(sim, 4),
                description=entry.description,
                peak_flux=entry.peak_flux,
                duration_min=entry.duration_min,
                narrative=narrative,
            ))
        return matches

    # ── Canonical event seeding ───────────────────────────────────────────

    def _seed_canonical_events(self) -> None:
        """Populate the database with ~50 canonical historical flare profiles."""
        from src.vectordb.embedder import StatisticalEmbedder
        embedder = StatisticalEmbedder(self.embedding_dim)

        for event in CANONICAL_EVENTS:
            # Generate a synthetic FRED light curve from the event parameters
            lc = _generate_fred_profile(
                peak_flux=event["peak_flux"],
                duration_min=event["duration_min"],
                rise_fraction=event.get("rise_frac", 0.2),
                cadence_s=60,
            )
            emb = embedder.embed(lc)

            entry = HistoricalFlareEntry(
                event_id=event["id"],
                event_name=event["name"],
                date=event["date"],
                flare_class=event["class"],
                peak_flux=event["peak_flux"],
                duration_min=event["duration_min"],
                description=event["description"],
                embedding=emb,
            )
            self.add_event(entry)


# ── FRED profile generator ───────────────────────────────────────────────────

def _generate_fred_profile(
    peak_flux: float,
    duration_min: float,
    rise_fraction: float = 0.2,
    cadence_s: float = 60,
    background: float = 1e-7,
) -> np.ndarray:
    """
    Generate a Fast Rise Exponential Decay (FRED) light curve.

    Parameters
    ----------
    peak_flux : float
        Peak flux value (W/m²).
    duration_min : float
        Total flare duration in minutes.
    rise_fraction : float
        Fraction of duration spent in the rise phase.
    cadence_s : float
        Time cadence in seconds.
    background : float
        Quiescent background flux.

    Returns
    -------
    np.ndarray
        Flux array of shape (N,).
    """
    duration_s = duration_min * 60
    n_points = max(int(duration_s / cadence_s), 10)
    t = np.linspace(0, duration_s, n_points)

    rise_end = duration_s * rise_fraction
    tau_rise = rise_end / 3.0
    tau_decay = (duration_s - rise_end) / 3.0

    flux = np.where(
        t <= rise_end,
        peak_flux * (1 - np.exp(-t / max(tau_rise, 1e-6))),
        peak_flux * np.exp(-(t - rise_end) / max(tau_decay, 1e-6)),
    )

    return (flux + background).astype(np.float64)


# ── Narrative builder ─────────────────────────────────────────────────────────

def _build_narrative(name: str, date: str, flare_class: str, similarity: float) -> str:
    """Build a human-readable comparison narrative."""
    pct = int(similarity * 100)
    if similarity >= 0.90:
        intensity = "near-identical"
    elif similarity >= 0.75:
        intensity = "strongly similar"
    elif similarity >= 0.60:
        intensity = "moderately similar"
    else:
        intensity = "weakly similar"

    return (
        f"Current precursor is {intensity} ({pct}% match) to the "
        f"{name} ({date}, class {flare_class})."
    )


